//! Small, font-independent toolbar icons on a shared 16px stroke grid.
use gpui::{canvas, div, point, prelude::*, px, AnyElement, Hsla, PathBuilder};

type Stroke = &'static [(f32, f32)];

/// Render common workbench symbols as vectors, retaining text for uncommon
/// menu glyphs until they have a dedicated shape.
pub fn icon(glyph: &'static str, color: Hsla) -> AnyElement {
    let strokes: &[Stroke] = match glyph {
        "◈" => &[
            &[(8., 1.), (15., 8.), (8., 15.), (1., 8.), (8., 1.)],
            &[(8., 4.), (12., 8.), (8., 12.), (4., 8.), (8., 4.)],
        ],
        "⌘" => &[
            &[(6., 3.), (2., 8.), (6., 13.)],
            &[(10., 3.), (14., 8.), (10., 13.)],
        ],
        "□" => &[
            &[
                (3., 2.),
                (10., 2.),
                (13., 5.),
                (13., 14.),
                (3., 14.),
                (3., 2.),
            ],
            &[(10., 2.), (10., 5.), (13., 5.)],
        ],
        "✦" => &[&[
            (8., 1.),
            (10., 6.),
            (15., 8.),
            (10., 10.),
            (8., 15.),
            (6., 10.),
            (1., 8.),
            (6., 6.),
            (8., 1.),
        ]],
        "folder" => &[&[
            (1., 4.),
            (6., 4.),
            (8., 6.),
            (15., 6.),
            (15., 13.),
            (1., 13.),
            (1., 4.),
        ]],
        "▸" => &[&[(6., 4.), (10., 8.), (6., 12.)]],
        "+" => &[&[(8., 3.), (8., 13.)], &[(3., 8.), (13., 8.)]],
        "×" => &[&[(4., 4.), (12., 12.)], &[(12., 4.), (4., 12.)]],
        "☰" | "◧" => &[
            &[(2., 3.), (14., 3.), (14., 13.), (2., 13.), (2., 3.)],
            &[(6., 3.), (6., 13.)],
        ],
        "▱" => &[
            &[(2., 3.), (14., 3.), (14., 13.), (2., 13.), (2., 3.)],
            &[(2., 10.), (14., 10.)],
        ],
        "◫" => &[
            &[(2., 3.), (14., 3.), (14., 13.), (2., 13.), (2., 3.)],
            &[(8., 3.), (8., 13.)],
        ],
        "⊟" => &[
            &[(2., 3.), (14., 3.), (14., 13.), (2., 13.), (2., 3.)],
            &[(2., 8.), (14., 8.)],
        ],
        "↗" => &[&[(4., 12.), (12., 4.)], &[(5., 4.), (12., 4.), (12., 11.)]],
        "↙" => &[&[(12., 4.), (4., 12.)], &[(4., 5.), (4., 12.), (11., 12.)]],
        "‹" => &[&[(10., 3.), (5., 8.), (10., 13.)]],
        "▾" => &[&[(4., 6.), (8., 10.), (12., 6.)]],
        "▴" => &[&[(4., 10.), (8., 6.), (12., 10.)]],
        "✎" => &[
            &[
                (3., 10.),
                (10., 3.),
                (13., 6.),
                (6., 13.),
                (3., 13.),
                (3., 10.),
            ],
            &[(8., 5.), (11., 8.)],
        ],
        "☑" => &[
            &[(12., 8.), (12., 13.), (2., 13.), (2., 3.), (9., 3.)],
            &[(5., 7.), (8., 10.), (14., 3.)],
        ],
        "±" => &[
            &[(3., 5.), (13., 5.)],
            &[(8., 1.), (8., 9.)],
            &[(3., 13.), (13., 13.)],
        ],
        ">_" => &[&[(2., 4.), (6., 8.), (2., 12.)], &[(8., 12.), (14., 12.)]],
        "≣" | "▤" => &[
            &[(3., 4.), (13., 4.)],
            &[(3., 8.), (13., 8.)],
            &[(3., 12.), (10., 12.)],
        ],
        "⊡" => &[
            &[(2., 3.), (14., 3.), (14., 13.), (2., 13.), (2., 3.)],
            &[(10., 3.), (10., 13.)],
        ],
        "▶" => &[&[(5., 3.), (13., 8.), (5., 13.), (5., 3.)]],
        "⌕" => &[&[(10., 10.), (14., 14.)]],
        "⚙" => &[&[
            (6., 2.),
            (10., 2.),
            (10., 4.),
            (12., 6.),
            (14., 6.),
            (14., 10.),
            (12., 10.),
            (10., 12.),
            (10., 14.),
            (6., 14.),
            (6., 12.),
            (4., 10.),
            (2., 10.),
            (2., 6.),
            (4., 6.),
            (6., 4.),
            (6., 2.),
        ]],
        "◎" | "react" => &[],
        _ => return div().text_color(color).child(glyph).into_any_element(),
    };
    canvas(
        |_, _, _| (),
        move |bounds, (), window, _| {
            let mut builder = PathBuilder::stroke(px(1.25));
            let at = |x, y| bounds.origin + point(px(x), px(y));
            for stroke in strokes {
                if let Some((first, rest)) = stroke.split_first() {
                    builder.move_to(at(first.0, first.1));
                    for &(x, y) in rest {
                        builder.line_to(at(x, y));
                    }
                }
            }
            if glyph == "react" {
                for rotation in [
                    0.0_f32,
                    std::f32::consts::PI / 3.0,
                    2.0 * std::f32::consts::PI / 3.0,
                ] {
                    for step in 0..=48 {
                        let angle = step as f32 * std::f32::consts::TAU / 48.0;
                        let x = 7.0 * angle.cos();
                        let y = 2.6 * angle.sin();
                        let p = at(
                            8.0 + x * rotation.cos() - y * rotation.sin(),
                            8.0 + x * rotation.sin() + y * rotation.cos(),
                        );
                        if step == 0 {
                            builder.move_to(p);
                        } else {
                            builder.line_to(p);
                        }
                    }
                }
            }
            let circles: &[(f32, f32, f32)] = match glyph {
                "⌕" => &[(6.5, 6.5, 4.5)],
                "⚙" => &[(8., 8., 2.5)],
                "◎" => &[(8., 8., 6.), (8., 8., 2.)],
                "react" => &[(8., 8., 0.7)],
                _ => &[],
            };
            for &(x, y, radius) in circles {
                builder.move_to(at(x + radius, y));
                for step in 1..=32 {
                    let angle = step as f32 * std::f32::consts::TAU / 32.;
                    builder.line_to(at(x + radius * angle.cos(), y + radius * angle.sin()));
                }
            }
            if let Ok(path) = builder.build() {
                window.paint_path(path, color);
            }
        },
    )
    .size(px(16.0))
    .flex_none()
    .into_any_element()
}
